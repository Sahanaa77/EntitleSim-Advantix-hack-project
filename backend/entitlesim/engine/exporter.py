from __future__ import annotations
import json
from typing import Any, Dict, List, Optional, Tuple
from entitlesim.engine.model import ParsedModel


def export_regression_test(
    model: ParsedModel,
    minimal_trace: List[Dict[str, Any]],
    inv_id: str,
    short_id: str = "demo",
    expected: Any = None,
    observed: Any = None,
) -> Tuple[str, str]:
    """Generates a standalone, deterministic pytest regression test.
    The generated test passes when fixed=True, and fails when fixed=False.
    """
    clean_inv = inv_id.lower().replace("-", "_")
    filename = f"test_regression_{clean_inv}_{short_id}.py"

    trace_json_str = json.dumps(minimal_trace, indent=4)
    model_raw_str = json.dumps(model.raw, indent=4)

    expected_str = json.dumps(expected) if expected is not None else "Plan features match expected oracle"
    observed_str = json.dumps(observed) if observed is not None else "Unauthorized state divergence"

    content = f'''# Generated by EntitleSim — Counterexample Regression Test
# Target Invariant: {inv_id}
# Expected: {expected_str}
# Observed: {observed_str}
# Replays isolated minimal counterexample sequence.

import pytest
from entitlesim.engine.model import parse_model
from entitlesim.engine.sut import EntitlementService
from entitlesim.engine.reference import ReferenceOracle
from entitlesim.engine.invariants import check_all_invariants

MODEL_DEFINITION = {model_raw_str}

MINIMAL_TRACE = {trace_json_str}


def run_counterexample_trace(fixed: bool):
    model = parse_model(MODEL_DEFINITION)
    sut = EntitlementService(fixed=fixed, model=model)
    oracle = ReferenceOracle(model)

    from entitlesim.engine.events import Event
    events = [Event.from_dict(d) for d in MINIMAL_TRACE]
    delivered = []
    violations = []

    for step_num, ev in enumerate(events, 1):
        pre_snapshots = {{t: sut.get_tenant_snapshot(t) for t in model.tenants}}
        sut.handle_event(ev)
        delivered.append(ev)

        expected_states = oracle.compute_state(delivered)
        step_violations = check_all_invariants(
            step=step_num,
            event=ev,
            sut=sut,
            expected_states=expected_states,
            model=model,
            pre_event_snapshots=pre_snapshots,
        )
        for v in step_violations:
            if v.id == "{inv_id}":
                violations.append(v)

    return violations


def test_regression_{clean_inv}_passes_when_fixed():
    """Verify that with entitlement fixes applied, zero violations occur."""
    violations = run_counterexample_trace(fixed=True)
    assert len(violations) == 0, f"Expected 0 violations with fixed=True, found: {{[v.message for v in violations]}}"


def test_regression_{clean_inv}_fails_on_buggy_sut():
    """Verify that the counterexample faithfully reproduces the invariant failure on buggy code."""
    violations = run_counterexample_trace(fixed=False)
    assert len(violations) > 0, "Counterexample should catch the bug when fixed=False"
'''
    return filename, content


def export_json(
    minimal_trace: List[Dict[str, Any]],
    inv_id: str,
    short_id: str = "demo",
) -> Tuple[str, str]:
    clean_inv = inv_id.lower().replace("-", "_")
    filename = f"counterexample_{clean_inv}_{short_id}.json"
    data = {
        "invariant_id": inv_id,
        "minimal_trace": minimal_trace,
    }
    return filename, json.dumps(data, indent=2)


def export_suite(
    model: ParsedModel,
    counterexamples: List[Dict[str, Any]],
) -> List[Dict[str, str]]:
    """Exports a single consolidated pytest suite test_entitlesim_suite.py
    and ready-to-run GitHub Actions workflow .github/workflows/entitlesim.yml.
    """
    model_raw_str = json.dumps(model.raw, indent=4)
    cx_list_str = json.dumps(counterexamples, indent=4)

    suite_code = f'''# Consolidated EntitleSim Verification Regression Suite
# Automatically generated for CI/CD pipelines.

import pytest
from entitlesim.engine.model import parse_model
from entitlesim.engine.sut import EntitlementService
from entitlesim.engine.reference import ReferenceOracle
from entitlesim.engine.invariants import check_all_invariants
from entitlesim.engine.events import Event

MODEL_DEFINITION = {model_raw_str}
COUNTEREXAMPLES = {cx_list_str}


@pytest.mark.parametrize("cx", COUNTEREXAMPLES, ids=[f"{{c['invariant_id']}}_{{c.get('id', i)}}" for i, c in enumerate(COUNTEREXAMPLES)])
def test_counterexample_remediation(cx):
    model = parse_model(MODEL_DEFINITION)
    sut = EntitlementService(fixed=True, model=model)
    oracle = ReferenceOracle(model)

    events = [Event.from_dict(d) for d in cx["minimal_trace"]]
    delivered = []

    for step_num, ev in enumerate(events, 1):
        pre_snapshots = {{t: sut.get_tenant_snapshot(t) for t in model.tenants}}
        sut.handle_event(ev)
        delivered.append(ev)

        expected_states = oracle.compute_state(delivered)
        step_violations = check_all_invariants(
            step=step_num,
            event=ev,
            sut=sut,
            expected_states=expected_states,
            model=model,
            pre_event_snapshots=pre_snapshots,
        )
        target_violations = [v for v in step_violations if v.id == cx["invariant_id"]]
        assert len(target_violations) == 0, f"Counterexample {{cx['invariant_id']}} violated on fixed service: {{[v.message for v in target_violations]}}"
'''

    github_workflow = """name: EntitleSim Invariant Verification

on:
  push:
    branches: [main, master]
  pull_request:
    branches: [main, master]

jobs:
  verify-entitlements:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4

      - name: Set up Python
        uses: actions/setup-python@v5
        with:
          python-version: "3.12"
          cache: "pip"

      - name: Install dependencies
        run: |
          python -m pip install --upgrade pip
          pip install -e ".[dev]"

      - name: Run EntitleSim Regression Suite
        run: |
          pytest -v tests/test_entitlesim_suite.py
"""

    return [
        {"filename": "test_entitlesim_suite.py", "content": suite_code},
        {"filename": ".github/workflows/entitlesim.yml", "content": github_workflow},
    ]
